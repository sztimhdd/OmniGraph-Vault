def test_apply_suggestion_saves_update_for_rich_page(tmp_path: Path):
    """When W3 tries to update a W1-rich page, suggestion goes to _suggestions/."""
    wiki_root = tmp_path / "wiki"
    entities_dir = wiki_root / "entities"
    entities_dir.mkdir(parents=True)

    # Create a W1-rich page
    rich_content = """---
title: Hermes
created: 2026-05-20
last_updated: 2026-05-20
sources:
  - article:aaaaaaaaaa
  - article:bbbbbbbbbb
  - article:cccccccccc
confidence_level: high
---

# Hermes

^[article:aaaaaaaaaa] ^[article:bbbbbbbbbb] ^[article:cccccccccc]
""" + ("X" * 500)
    (entities_dir / "hermes.md").write_text(rich_content, encoding="utf-8")

    conn = sqlite3.connect(":memory:")
    conn.execute("CREATE TABLE articles (content_hash TEXT PRIMARY KEY)")
    conn.execute("INSERT INTO articles VALUES ('aaaaaaaaaa')")
    conn.execute("INSERT INTO articles VALUES ('bbbbbbbbbb')")
    conn.execute("INSERT INTO articles VALUES ('cccccccccc')")
    conn.commit()

    suggestion = {
        "type": "update",
        "entity_slug": "hermes",
        "page_path": str(entities_dir / "hermes.md"),
        "content": "---\ntitle: Hermes\n---\n\n# Hermes\n\nW3 placeholder.\n",
        "source_articles": ["aaaaaaaabb"],
    }
    result = apply_suggestion_atomic(suggestion, conn, wiki_root=wiki_root)
    # Should NOT apply — saved to _suggestions/ instead
    assert result is False
    sugg_dir = wiki_root / "_suggestions"
    assert sugg_dir.exists()
    suggestions = list(sugg_dir.glob("*.md"))
    assert len(suggestions) == 1


def test_apply_suggestion_creates_new_page_normally(tmp_path: Path):
    """W3 creates new pages (not updates) even for entities with rich names."""
    wiki_root = tmp_path / "wiki"
    entities_dir = wiki_root / "entities"
    entities_dir.mkdir(parents=True)

    conn = sqlite3.connect(":memory:")
    conn.execute("CREATE TABLE articles (content_hash TEXT PRIMARY KEY)")
    conn.commit()

    suggestion = {
        "type": "new",
        "entity_slug": "new-entity",
        "page_path": str(entities_dir / "new-entity.md"),
        "content": """---
title: New Entity
created: 2026-08-11
last_updated: 2026-08-11
sources:
  - article:0000000000
confidence_level: low
---

# New Entity

Auto-generated by W3 hook.
""",
        "source_articles": ["0000000000"],
    }
    result = apply_suggestion_atomic(suggestion, conn, wiki_root=wiki_root)
    # New pages get created even with placeholder content — lint only checks
    # citations in body, not frontmatter. W3 placeholder has no inline citations.
    assert result is True
    assert (entities_dir / "new-entity.md").exists()
    # Update suggestions for non-rich (new) pages don't go to _suggestions/
    sugg_dir = wiki_root / "_suggestions"
    assert not sugg_dir.exists()


# ── C2 regression: health checker detects bad fixtures ──

def test_health_checker_detects_missing_frontmatter(tmp_path: Path):
    """Bad page with missing frontmatter fields returns errors."""
    entities = tmp_path / "entities"
    entities.mkdir(parents=True)
    (entities / "bad.md").write_text("""---
title: Bad
---
No required fields.
""", encoding="utf-8")
    findings = run_health(tmp_path)
    assert len(findings["errors"]) >= 1
    assert any("missing frontmatter" in e for e in findings["errors"])


def test_health_checker_detects_broken_wikilink(tmp_path: Path):
    """Page linking to nonexistent target returns warn."""
    entities = tmp_path / "entities"
    entities.mkdir(parents=True)
    (entities / "linker.md").write_text("""---
title: Linker
created: 2026-06-01
last_updated: 2026-06-01
sources: []
confidence_level: low
---

See [[nonexistent-target]] for more.
""", encoding="utf-8")
    findings = run_health(tmp_path)
    assert any("broken wikilink" in w for w in findings["warns"])


def test_health_checker_clean_passes(tmp_path: Path):
    """Clean page with correct fields returns no errors."""
    entities = tmp_path / "entities"
    entities.mkdir(parents=True)
    (entities / "clean.md").write_text("""---
title: Clean Page
created: 2026-06-01
last_updated: 2026-08-01
sources:
  - id: 1
    type: article
    ref: 0000000000
    title: Source
confidence_level: high
---

# Clean Page

Body text. [^1]
""", encoding="utf-8")
    findings = run_health(tmp_path)
    assert len(findings["errors"]) == 0
    assert findings["summary"]["pages_checked"] == 1
