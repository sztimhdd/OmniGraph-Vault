# ── C1 regression: article-identity hash contract ──

def test_batch_hashes_are_10_char_md5():
    """batch_ingest_from_spider must use 10-char MD5(url) not 16-char SHA256."""
    import hashlib
    url = "https://mp.weixin.qq.com/s/test"
    h = hashlib.md5(url.encode()).hexdigest()[:10]
    assert len(h) == 10
    assert all(c in "0123456789abcdef" for c in h)

    # Checkpoint hash (different domain) stays 16-char for file I/O
    from lib.checkpoint import get_article_hash
    ckpt = get_article_hash(url)
    assert len(ckpt) == 16
    assert ckpt != h


# ── C5 regression: W1-rich page protection ──

def test_page_is_w1_rich_detects_w1_synthesis(tmp_path: Path):
    """A page with >=3 citations and >500 chars body is W1-rich."""
    content = """---
title: Test Entity
created: 2026-05-20
last_updated: 2026-05-20
sources:
  - article:aaaaaaaaaa
  - article:bbbbbbbbbb
  - article:cccccccccc
confidence_level: high
---

# Test Entity

This is a detailed W1 synthesis page with three citations:
^[article:aaaaaaaaaa] discusses the origin. ^[article:bbbbbbbbbb] covers
the implementation. ^[article:cccccccccc] provides benchmarks.

""" + ("X" * 500)
    page = tmp_path / "test.md"
    page.write_text(content, encoding="utf-8")
    assert _page_is_w1_rich(page) is True


